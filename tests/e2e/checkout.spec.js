import { test, expect, BOAT_ID, NOW, RESERVATION_ID, completeContact, method, openMethod, summary } from './reservationsFixture.js'

const posts = (state, suffix) => state.requests.filter((r) => r.method === 'POST' && r.path.endsWith(suffix))
const storedCheckout = (page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('seashare.checkout.v1')))

test('las fotos aparecen en catálogo y detalle directo, incluso con M2 antiguo', async ({ page, state }) => {
  await page.goto('/explorar')
  await expect(page.getByRole('img', { name: 'Barco de prueba', exact: true })).toBeVisible()
  await page.goto(`/explorar/${BOAT_ID}`)
  await expect(page.getByRole('img', { name: 'Barco de prueba', exact: true })).toBeVisible()
  expect(state.requests.some((r) => r.path === `/api/m1/api/v1/vessels/${BOAT_ID}`)).toBe(true)
})

test('el acceso directo rechaza fechas pasadas y exige consentimiento', async ({ page, state }) => {
  await page.goto(summary.replace('2026-11-22', '2026-11-20'))
  await expect(page.getByRole('alert')).toContainText('Elige fechas desde hoy')
  expect(posts(state, '/reservations')).toHaveLength(0)
  await page.goto(method)
  await expect(page.getByRole('heading', { name: 'Pago', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirmar y Pagar' })).toBeDisabled()
})

test('hoy no permite una hora pasada, tampoco dentro del antiguo margen de cinco minutos', async ({ page, state }) => {
  await openMethod(page, summary.replace('2026-11-22', '2026-11-21'))
  await page.getByLabel('Nombre completo del contacto *', { exact: true }).fill('TEST CONTACT')
  await page.getByLabel('Teléfono de contacto *', { exact: true }).fill('3001234567')
  const input = page.getByLabel('Hora de salida *', { exact: true })
  await expect(input).toHaveAttribute('min', '08:31')
  await input.fill('08:28')
  await expect(page.getByText('La salida debe ser posterior', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar al formulario seguro' })).toBeDisabled()
  expect(posts(state, '/reservations')).toHaveLength(0)
  await input.fill('08:31')
  await page.clock.fastForward(61000)
  await expect(page.getByRole('button', { name: 'Continuar al formulario seguro' })).toBeDisabled()
})

test('recargar y volver conserva ID, clave y vencimiento sin duplicar ni almacenar datos sensibles', async ({ page, state }) => {
  await openMethod(page)
  await completeContact(page)
  const original = await storedCheckout(page)
  expect(original.reservationId).toBe(RESERVATION_ID)
  await page.reload()
  await expect(page.getByLabel('Nombre completo del contacto *', { exact: true })).toBeVisible()
  await completeContact(page)
  expect(posts(state, '/reservations')).toHaveLength(1)
  const restored = await storedCheckout(page)
  expect(restored.idempotencyKey).toBe(original.idempotencyKey)
  expect(restored.expiresAt).toBe(original.expiresAt)
  expect(restored.serverExpiresAt).toBe(original.serverExpiresAt)
  const storage = await page.evaluate(() => JSON.stringify({ ...sessionStorage }))
  for (const secret of ['TEST CONTACT', '3001234567', 'e2e-synthetic-token', 'payer-e2e@example.com']) expect(storage).not.toContain(secret)
  await page.getByRole('button', { name: '‹ Volver al resumen' }).click()
  expect(posts(state, '/abandonment')).toHaveLength(0)
})

test('salir del checkout descarta una iniciada, pero no solicita una cancelación financiera', async ({ page, state }) => {
  await openMethod(page)
  await completeContact(page)
  await page.getByRole('button', { name: 'Salir del checkout', exact: true }).click()
  await expect(page).toHaveURL(/\/explorar$/)
  expect(posts(state, '/abandonment')).toHaveLength(1)
  expect(state.status).toBe('EXPIRED')
  expect(posts(state, '/cancellation')).toHaveLength(0)
  expect(posts(state, '/payments')).toHaveLength(0)
  await page.goto('/mis-reservas')
  await expect(page.getByText('No tienes reservas en esta vista.')).toBeVisible()
  await page.getByRole('tab', { name: 'Canceladas', exact: true }).click()
  await expect(page.getByText('Expirada', { exact: true })).toBeVisible()
})

