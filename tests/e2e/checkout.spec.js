test('vencer desmonta el SDK y recargar no renueva los quince minutos', async ({ page, state }) => {
  await openMethod(page)
  await completeContact(page)
  const original = await storedCheckout(page)
  await page.clock.fastForward(901000)
  await expect(page.getByRole('timer')).toContainText('EXPIRÓ')
  await expect(page.getByTestId('sdk-stub')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('timer')).toContainText('EXPIRÓ')
  expect((await storedCheckout(page)).expiresAt).toBe(original.expiresAt)
  expect(posts(state, '/reservations')).toHaveLength(1)
})

test('un pago enviado no se abandona al navegar y el doble callback no lo duplica', async ({ page, state }) => {
  await openMethod(page)
  await completeContact(page)
  expect(await page.evaluate(() => window.__mpTest.settings.initialization.amount)).toBe(280500)
  await page.evaluate(() => { void window.__mpTest.submitDuplicate().catch(() => {}) })
  await expect.poll(() => posts(state, '/payments').length).toBe(1)
  expect(await page.evaluate(() => window.__mpTest.duplicateShared)).toBe(true)
  await page.getByRole('button', { name: 'Salir del checkout', exact: true }).click()
  await expect(page).toHaveURL(/\/explorar$/)
  expect(posts(state, '/abandonment')).toHaveLength(0)
  await page.goto('/mis-reservas')
  await expect(page.getByText('Pendiente de pago', { exact: true })).toBeVisible()
})

test('una creación con respuesta perdida reutiliza la misma clave en el reintento', async ({ page, state }) => {
  state.loseCreateResponse = true
  await openMethod(page)
  await page.getByLabel('Nombre completo del contacto *', { exact: true }).fill('TEST CONTACT')
  await page.getByLabel('Teléfono de contacto *', { exact: true }).fill('3001234567')
  await page.getByLabel('Hora de salida *', { exact: true }).fill('10:00')
  await page.getByRole('button', { name: 'Continuar al formulario seguro' }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo conectar')
  await page.getByRole('button', { name: 'Continuar al formulario seguro' }).click()
  await expect(page.getByTestId('sdk-stub')).toBeVisible()
  const requests = posts(state, '/reservations')
  expect(requests).toHaveLength(2)
  expect(requests[0].headers['idempotency-key']).toBe(requests[1].headers['idempotency-key'])
})

